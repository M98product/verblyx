-- 1. Chaque compte reçoit un numéro unique (affiché VX-00001, VX-00002…)
alter table public.learners add column if not exists account_no bigint generated by default as identity;
create unique index if not exists learners_account_no_key on public.learners (account_no);
alter table public.learners add column if not exists created_at timestamptz not null default now();

-- 2. Les cadeaux envoyés par l'admin (XP, vies, pièces, niveau).
--    L'appli de l'élève les récupère et les applique toute seule.
alter table public.learners add column if not exists gifts jsonb not null default '[]'::jsonb;

-- 3. La liste des administrateurs (personne ne peut la lire ni la modifier depuis le site)
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- Tous les comptes (réservé aux admins)
create or replace function public.admin_list()
returns table (id uuid, account_no bigint, email text, signed_up timestamptz, last_sign_in timestamptz, profile jsonb, gifts jsonb)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Accès réservé aux administrateurs'; end if;
  return query
    select u.id, l.account_no, u.email::text, u.created_at, u.last_sign_in_at,
           coalesce(l.profile, '{}'::jsonb), coalesce(l.gifts, '[]'::jsonb)
    from auth.users u left join public.learners l on l.id = u.id
    order by u.created_at desc;
end $$;

-- Envoyer un cadeau à un élève (réservé aux admins)
create or replace function public.admin_gift(p_target uuid, p_kind text, p_amount int default 0, p_level text default null)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Accès réservé aux administrateurs'; end if;
  if p_kind not in ('xp', 'coins', 'hearts', 'level') then raise exception 'Type de cadeau inconnu'; end if;
  if p_kind = 'level' and (p_level is null or p_level not in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')) then raise exception 'Niveau inconnu'; end if;
  if p_kind <> 'level' and (p_amount is null or p_amount < -100000 or p_amount > 100000) then raise exception 'Quantité invalide'; end if;
  update public.learners
     set gifts = gifts || jsonb_build_array(jsonb_build_object('kind', p_kind, 'n', p_amount, 'level', p_level, 'at', now()))
   where id = p_target;
  if not found then raise exception 'Ce compte n''a pas encore de profil'; end if;
end $$;

-- L'élève récupère ses cadeaux (et la liste est vidée en même temps)
create or replace function public.claim_gifts() returns jsonb
language plpgsql security definer set search_path = public as $$
declare g jsonb;
begin
  select gifts into g from public.learners where id = auth.uid() for update;
  if g is null or g = '[]'::jsonb then return '[]'::jsonb; end if;
  update public.learners set gifts = '[]'::jsonb where id = auth.uid();
  return g;
end $$;

revoke all on function public.is_admin(), public.admin_list(), public.admin_gift(uuid, text, int, text), public.claim_gifts() from public, anon;
grant execute on function public.is_admin(), public.admin_list(), public.admin_gift(uuid, text, int, text), public.claim_gifts() to authenticated;

-- 4. Ton compte admin : inscris-toi d'abord sur le site avec cette adresse, puis lance ce fichier.
insert into public.admins (user_id)
select id from auth.users where email = 'admin@verblyx.app'
on conflict do nothing;
